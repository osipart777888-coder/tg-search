"""Conservative public-text scope filter, not a person's geolocation."""
import re


# These are textual hints, not a complete gazetteer. Ambiguous or absent hints
# are excluded. Language, usernames, phone prefixes and DC IDs are not evidence.
_RUSSIA = re.compile(r'(?<!\w)(?:росси(?:я|и|ю|ей)|российск[а-яё]*|рф|russia|russian federation)(?!\w)|🇷🇺', re.I)
_REGIONS = re.compile(
    r'(?<!\w)(?:москв[а-яё]*|подмосков[а-яё]*|санкт[ -]петербург[а-яё]*|спб|'
    r'ленинградск[а-яё]*|новосибирск[а-яё]*|екатеринбург[а-яё]*|нижн(?:ий|его|ем) новгород[а-яё]*|'
    r'казан[ьи]|татарстан[а-яё]*|красноярск[а-яё]*|челябинск[а-яё]*|самар[а-яё]*|'
    r'омск[а-яё]*|ростов[ -]на[ -]дону|ростовск[а-яё]*|уф[аыеу]|башкортостан[а-яё]*|'
    r'краснодар[а-яё]*|воронеж[а-яё]*|перм[ьи]|волгоград[а-яё]*|саратов[а-яё]*|'
    r'тюмен[ьи]|тольятти|ижевск[а-яё]*|барнаул[а-яё]*|ульяновск[а-яё]*|иркутск[а-яё]*|'
    r'хабаровск[а-яё]*|владивосток[а-яё]*|ярославл[ьяею]|махачкал[а-яё]*|томск[а-яё]*|'
    r'оренбург[а-яё]*|кемеров[а-яё]*|новокузнецк[а-яё]*|рязан[ьи]|астрахан[ьи]|'
    r'пенза|пензе|пензенск[а-яё]*|липецк[а-яё]*|калининград[а-яё]*|тул[аыуе]|'
    r'курск[а-яё]*|сочи|твер[ьи]|брянск[а-яё]*|иваново|ивановск[а-яё]*|'
    r'белгород[а-яё]*|владимирск[а-яё]*|архангельск[а-яё]*|мурманск[а-яё]*|'
    r'вологд[а-яё]*|смоленск[а-яё]*|костром[а-яё]*|тамбов[а-яё]*|петрозаводск[а-яё]*|'
    r'саранск[а-яё]*|чебоксар[а-яё]*|йошкар[ -]ол[а-яё]*|сыктывкар[а-яё]*|'
    r'якутск[а-яё]*|саха|якутия|бурятия|улан[ -]удэ|чита|забайкальск[а-яё]*|'
    r'сахалин[а-яё]*|камчатк[а-яё]*|магадан[а-яё]*|дагестан[а-яё]*|чечн[яеию]|'
    r'грозн(?:ый|ого|ом)|ингушетия|адыгея|калмыкия|элиста|тува|тыва|хакасия|'
    r'ханты[ -]мансийск[а-яё]*|хмао|янао|ямал[а-яё]*|карелия|алтайск[а-яё]*|'
    r'moscow|saint petersburg|novosibirsk|kazan|yekaterinburg)(?!\w)', re.I)
_OTHER_SCOPE = re.compile(
    r'(?<!\w)(?:казахстан[а-яё]*|алмат[а-яё]*|астан[а-яё]*|беларус[а-яё]*|белорусс[а-яё]*|минск[а-яё]*|'
    r'украин[а-яё]*|киев[а-яё]*|київ[а-яё]*|узбекистан[а-яё]*|ташкент[а-яё]*|киргиз[а-яё]*|кыргыз[а-яё]*|'
    r'бишкек[а-яё]*|таджикистан[а-яё]*|душанбе|армени[а-яё]*|ереван[а-яё]*|грузи[а-яё]*|тбилиси|'
    r'азербайджан[а-яё]*|баку|молдов[а-яё]*|турци[а-яё]*|стамбул[а-яё]*|антали[а-яё]*|'
    r'германи[а-яё]*|берлин[а-яё]*|польш[а-яё]*|варшав[а-яё]*|сша|оаэ|дуба[йиея]|'
    r'kazakhstan|belarus|ukraine|uzbekistan|kyrgyzstan|armenia|georgia|turkey|germany|usa|uae)(?!\w)|'
    r'🇰🇿|🇧🇾|🇺🇦|🇺🇿|🇰🇬|🇹🇯|🇦🇲|🇬🇪|🇦🇿|🇹🇷|🇩🇪|🇺🇸|🇦🇪', re.I)
_NEGATED = re.compile(r'(?<!\w)(?:вне|кроме|исключая|не работаем (?:в|по))\s+(?:росси[а-яё]*|рф)(?!\w)', re.I)


def russia_basis(title, about=''):
    """Return a visible match; unknown/mixed/negated scope stays excluded."""
    text = re.sub(r'https?://\S+|(?:@|t\.me/)\w+', ' ', title + '\n' + about)
    if _OTHER_SCOPE.search(text) or _NEGATED.search(text):
        return ''
    for label, value in (('Название', title), ('Описание', about)):
        value = re.sub(r'https?://\S+|(?:@|t\.me/)\w+', ' ', value)
        match = _RUSSIA.search(value) or _REGIONS.search(value)
        if match:
            return f'{label}: «{match.group()}»'
    return ''
